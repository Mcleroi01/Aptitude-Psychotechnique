import type { Difficulty } from "../../generated/prisma/enums";

type Pedagogy = {
  explanation: string;
  classicMethod: string;
  quickMethod: string;
  tip: string;
  commonMistakes: string;
};

type Base = { category: string; difficulty: Difficulty; prompt: string } & Pedagogy;

export type SeedQuestion =
  | (Base & { type: "SINGLE_CHOICE"; options: string[]; answer: number })
  | (Base & { type: "TRUE_FALSE"; answer: boolean })
  | (Base & { type: "NUMERIC"; value: number; tolerance?: number; unit?: string })
  | (Base & { type: "FILL_BLANK"; blanks: string[][] });

const SECONDS_BY_DIFFICULTY: Record<Difficulty, number> = { EASY: 30, MEDIUM: 45, HARD: 60 };

/** Données enregistrées pour une question du seed (même forme que l'éditeur). */
export function toSeedQuestionData(q: SeedQuestion) {
  const base = {
    type: q.type,
    prompt: q.prompt,
    difficulty: q.difficulty,
    explanation: q.explanation,
    classicMethod: q.classicMethod,
    quickMethod: q.quickMethod,
    tip: q.tip,
    commonMistakes: q.commonMistakes,
    recommendedSeconds: SECONDS_BY_DIFFICULTY[q.difficulty],
  };
  switch (q.type) {
    case "SINGLE_CHOICE":
      return {
        ...base,
        answerKey: {},
        options: q.options.map((text, i) => ({ label: String.fromCharCode(65 + i), text, isCorrect: i === q.answer, order: i })),
      };
    case "TRUE_FALSE":
      return {
        ...base,
        answerKey: {},
        options: [
          { label: "V", text: "Vrai", isCorrect: q.answer, order: 0 },
          { label: "F", text: "Faux", isCorrect: !q.answer, order: 1 },
        ],
      };
    case "NUMERIC":
      return { ...base, answerKey: { value: q.value, tolerance: q.tolerance ?? 0, ...(q.unit && { unit: q.unit }) }, options: [] };
    case "FILL_BLANK":
      return { ...base, answerKey: { blanks: q.blanks.map((accepted) => ({ accepted })), caseSensitive: false }, options: [] };
  }
}

